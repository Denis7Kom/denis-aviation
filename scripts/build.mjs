import { build } from 'esbuild';
import { cp, mkdir, readdir, readFile, writeFile } from 'node:fs/promises';

const checking = process.argv.includes('--check');
const result = await build({
  entryPoints: ['src/main.js'],
  bundle: true,
  format: 'iife',
  target: ['es2022'],
  charset: 'utf8',
  legalComments: 'none',
  minify: false,
  write: false,
  banner: { js: '// Generated by npm run build. Edit src/, not this file.\n\"use strict\";' },
});
const output = result.outputFiles[0].text;
if (checking) {
  if (output !== (await readFile('app.js', 'utf8'))) {
    throw new Error('app.js is stale. Run npm run build and commit the result.');
  }
  console.log('PASS: app.js matches the source modules.');
} else {
  await writeFile('app.js', output);
}

if (!checking && process.env.WORKERS_CI === '1') {
  const directory = '.wrangler-public';
  await mkdir(directory, { recursive: true });
  const files = await readdir('.');
  for (const file of files) {
    if (/\.(?:html|css|js|svg|webmanifest)$/.test(file) || file === 'assets' || file === 'docs') {
      await cp(file, `${directory}/${file}`, { recursive: true });
    }
  }
}
